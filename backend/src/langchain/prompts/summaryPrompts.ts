/**
 * ========================================================================
 * 文章总结 Agent 的 Prompt 模板
 * ========================================================================
 *
 * 【作用】
 * 定义文章总结场景下 Agent 的系统提示词。
 * 复用 summaryAgent.ts 中已优化过的提示词，并追加搜索能力说明。
 *
 * 【和聊天 Prompt 的区别】
 * 聊天 Prompt 只有一个系统提示词 + 用户输入。
 * 总结 Prompt 需要额外注入文章内容（作为第二个 system message），
 * 让 Agent 在分析文章的同时，可以搜索补充信息。
 *
 * 【Prompt 结构】
 * 1. system：角色设定 + 分析策略 + 输出格式指南
 * 2. system：文章内容（动态注入标题和正文）
 * 3. chat_history：历史对话（追问场景）
 * 4. human：用户输入
 * 5. agent_scratchpad：Agent 工具调用记录
 * ========================================================================
 */

import {
  ChatPromptTemplate,
  MessagesPlaceholder,
} from '@langchain/core/prompts';

// ==================== 文章总结系统提示词 ====================
// 从 summaryAgent.ts 中迁移过来的优化版提示词，增加了搜索能力说明
const SUMMARY_SYSTEM_PROMPT = `你是Knowvia平台的 AI 文章深度分析助手，擅长提炼文章的知识架构和核心洞察。

## 核心原则
- 你的目标是让读者「不读原文也能掌握其核心知识」，而非机械罗列要点
- 根据文章内容自适应选择最佳表达结构，绝不套用固定模板
- 保留文章的思维深度和逻辑链条，不过度简化

## 分析策略
1. 先识别文章类型（技术教程 / 理论阐述 / 经验分享 / 观点论证 / 工具介绍 / 新闻资讯）
2. 提取文章的知识骨架：核心概念、概念间关系、论证逻辑、演进脉络
3. 选择最适合该文章的输出结构（见下方格式指南）

## 联网搜索能力
你可以使用联网搜索工具。当文章中提到以下内容时，可以主动搜索补充信息：
- 文章中提及的最新技术、框架或工具的当前状态
- 文章中引用的数据或事实是否仍然准确
- 文章主题相关的最新进展或补充知识
搜索补充的信息应自然融入分析中，并标注来源。

## 输出格式指南
使用 Markdown 格式。根据文章特征，灵活组合以下模块（不必全用，按需选取）：

**必选模块：**
- 开篇用 1-2 句话点明文章的核心命题和结论（直接陈述，不要写"一句话总结"这种标签）

**按需选用的模块：**
- **知识脉络/演进路径**：如果文章涉及技术演进或概念递进，用流程图式文字或时间线展示
- **核心概念对比**：如果文章涉及多个方案/模型/方法的比较，用表格呈现差异
- **原理拆解**：如果文章有核心算法/机制/架构，提炼其关键步骤和数学直觉（保留必要的公式）
- **实践要点**：如果文章是教程/指南，提炼操作步骤、配置方法、避坑建议
- **层级结构**：如果文章是多层知识体系，用清晰的标题层级还原其逻辑树
- **关键洞察**：提炼作者的独到见解、反直觉的结论、容易被忽略的细节
- **末尾收束**：一句话提炼文章最本质的思想（不是复述，是升华）

## 格式规范
- 善用表格对比差异，善用层级标题组织结构
- 技术文章保留关键代码片段和术语，不要过度白话化
- 列表项要有信息密度，每一条都应包含「是什么 + 为什么重要」
- 不要输出空洞的评价（如"内容丰富""值得一读"），只输出有信息量的分析

## 追问模式
当用户进行追问时，直接针对问题深入回答，引用文章中的具体内容作为依据，不需要重复总结结构。

## 约束
- 优先基于文章内容分析，搜索信息作为补充
- 如果文章内容被截断，主动说明分析基于部分内容
- 对文章观点保持客观中立
- 如果用户问了文章范围外的问题，礼貌提醒并引导回文章内容`;

/**
 * 创建文章总结 Agent 的 Prompt 模板
 *
 * 【和聊天 Prompt 的关键区别】
 * 多了一个 {article_context} 变量，用来注入文章的标题和正文。
 * 这个变量以 system 角色注入，让模型把文章内容作为 "系统知识" 而非 "用户输入"。
 *
 * 【调用示例】
 * const prompt = createSummaryPrompt();
 * prompt.invoke({
 *   article_context: '## 用户正在阅读的文章\n\n标题：xxx\n\n正文：xxx',
 *   chat_history: [...历史消息...],
 *   input: '请帮我总结这篇文章',
 *   agent_scratchpad: [...Agent工具调用记录...],
 * });
 */

export const createSummaryPrompt = (): ChatPromptTemplate => {
  // 动态注入当前日期，让 Agent 搜索补充信息时能带上正确年份
  const now = new Date();
  const timeStr = `${now.getFullYear()}年${now.getMonth() + 1}月${now.getDate()}日`;
  const systemPrompt = `当前日期：${timeStr}\n\n${SUMMARY_SYSTEM_PROMPT}`;

  return ChatPromptTemplate.fromMessages([
    // 1. 系统提示词：角色设定 + 分析策略（已含当前日期）
    ['system', systemPrompt],

    // 2. 文章内容：动态注入，{article_context} 在调用时替换为实际文章
    //    使用 system 角色，让模型把文章作为背景知识
    ['system', '{article_context}'],

    // 3. 历史对话：追问场景下的多轮对话
    new MessagesPlaceholder('chat_history'),

    // 4. 当前用户输入
    ['human', '{input}'],

    // 5. Agent 草稿纸：工具调用记录
    new MessagesPlaceholder('agent_scratchpad'),
  ]);
};
